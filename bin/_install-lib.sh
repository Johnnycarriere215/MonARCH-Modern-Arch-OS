#!/usr/bin/env bash
#
# Shared helpers for the monarch-install-* commands and monarch-app-install.
#
# Not a command — the leading underscore keeps it out of the dispatcher's scan.
# Source it after _lib.sh, with MONARCH_HOME already resolved.
#
# Golden rule 7: ship installers, not binaries. Nothing here downloads a
# redistributable-unfriendly package into the repo; every one of these fetches
# at install time on the user's own machine, which is a different legal
# position entirely and the reason these are scripts rather than ISO contents.

# Is it already there?
pkg_installed() {
  pacman -Q "$1" >/dev/null 2>&1
}

require_arch() {
  have pacman || die "this needs pacman — MonARCH runs on Arch"
}

# paru, or a clear reason why not. Every AUR installer routes through here so
# there is one message to get right rather than six.
require_aur() {
  require_arch
  have paru && return 0

  err "paru is not installed, and this package is in the AUR"
  printf '\n  paru is normally installed by bootstrap.sh stage 20. To add it now:\n' >&2
  printf '    sudo pacman -S --needed base-devel git\n' >&2
  printf '    git clone https://aur.archlinux.org/paru-bin.git /tmp/paru-bin\n' >&2
  printf '    cd /tmp/paru-bin && makepkg -si\n' >&2
  return 1
}

# Install from the AUR, or say it is already there. Not --noconfirm: an AUR
# build shows you a PKGBUILD for a reason, and an installer that hides it is
# an installer that installs whatever the AUR happened to contain today.
aur_install() {
  local pkg=$1 label=${2:-$1}

  if pkg_installed "$pkg"; then
    ok "$label is already installed"
    return 0
  fi

  require_aur || return 1

  info "Installing $label from the AUR ($pkg)"
  step "you will be shown the PKGBUILD — read it, that is the point of the AUR"
  paru -S --needed "$pkg" || { err "$label did not install"; return 1; }
  ok "$label installed"
}

repo_install() {
  local pkg=$1 label=${2:-$1}

  if pkg_installed "$pkg"; then
    ok "$label is already installed"
    return 0
  fi

  require_arch
  info "Installing $label ($pkg)"
  sudo pacman -S --needed --noconfirm "$pkg" || { err "$label did not install"; return 1; }
  ok "$label installed"
}

# ------------------------------------------------------------ desktop files ---

# XDG applications directory. Web apps and AppImages both land here so the
# launcher can see them.
MONARCH_APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
MONARCH_ICONS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/monarch"

# write_desktop <file> <Name> <Exec> <Icon> <Categories> [extra lines...]
write_desktop() {
  local file=$1 name=$2 exec_line=$3 icon=$4 categories=$5
  shift 5

  mkdir -p "$(dirname "$file")"
  {
    printf '[Desktop Entry]\n'
    printf '# GENERATED BY MONARCH — regenerate rather than edit\n'
    printf 'Type=Application\n'
    printf 'Name=%s\n' "$name"
    printf 'Exec=%s\n' "$exec_line"
    printf 'Icon=%s\n' "$icon"
    printf 'Categories=%s\n' "$categories"
    printf 'Terminal=false\n'
    local line
    for line in "$@"; do printf '%s\n' "$line"; done
  } >"$file"
  chmod 0644 "$file"

  # Without this the launcher will not see it until the next login on some
  # setups. Cheap, and silent when the tool is absent.
  have update-desktop-database && update-desktop-database "$MONARCH_APPS_DIR" 2>/dev/null || true
}

# ------------------------------------------------------------------- kvm ---

# Locked decision: Claude Desktop needs /dev/kvm, and Cowork fails SILENTLY
# without it — no error, features simply do not appear. Worth its own check
# because "it is broken and nothing said why" is the worst failure mode there
# is.
check_kvm() {
  if [[ ! -e /dev/kvm ]]; then
    loud "/dev/kvm does not exist."
    printf '\n  Claude Desktop needs it, and Cowork fails SILENTLY without it —\n' >&2
    printf '  no error message, the features just are not there.\n\n' >&2
    printf '  Usually one of:\n' >&2
    printf '    * VT-x disabled in the BIOS (EliteBook: Security > System Security)\n' >&2
    printf '    * running inside a VM without nested virtualisation\n' >&2
    printf '    * the kvm_intel module not loaded:  sudo modprobe kvm_intel\n\n' >&2
    return 1
  fi

  if [[ ! -r /dev/kvm || ! -w /dev/kvm ]]; then
    loud "/dev/kvm exists but you cannot use it."
    printf '\n  Add yourself to the kvm group and log out and back in:\n' >&2
    printf '    sudo usermod -aG kvm %s\n\n' "$USER" >&2
    return 1
  fi

  ok "/dev/kvm is present and usable"
}
